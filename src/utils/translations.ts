export type TranslationKey = keyof typeof TRANSLATIONS['en'];

/**
 * Returns translated string for a given key in the target language, falling back to English.
 */
export function getTranslation(key: TranslationKey, lang?: string): string {
  const norm = normalizeLanguage(lang);
  const bundle = TRANSLATIONS[norm] || TRANSLATIONS.en;
  return bundle[key] || TRANSLATIONS.en[key] || key;
}
