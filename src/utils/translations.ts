/**
 * Helper to translate genre names across languages
 */
export function getGenreTranslation(genre: string, lang?: string): string {
  const norm = normalizeLanguage(lang);
  const match = GENRE_TRANSLATIONS[genre];
  if (match && match[norm]) {
    return match[norm];
  }
  return genre;
}

