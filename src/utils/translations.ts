/**
 * Normalizes any language string (e.g. "French (FR)", "Français", "ar", "Arabic (AR)")
 * into our supported system language codes: 'en' | 'fr' | 'ar'.
 */
export function normalizeLanguage(lang?: string): SupportedLanguage {
  if (!lang) return 'en';
  const lower = lang.toLowerCase().trim();

  if (lower.startsWith('fr') || lower.includes('français') || lower.includes('french')) {
    return 'fr';
  }
  if (lower.startsWith('ar') || lower.includes('عربي') || lower.includes('arabic')) {
    return 'ar';
  }
  return 'en';
}

